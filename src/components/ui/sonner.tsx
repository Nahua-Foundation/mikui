"use client";

import { createPortal } from "react-dom";
import { Toaster as Sonner, ToasterProps } from "sonner";
import { useTheme } from "../../theme";

/**
 * Тост берёт тему у приложения, а не держит свою.
 *
 * Цвета ему задают переменные `--normal-*` ниже, и одних их хватило бы, но
 * `theme` у sonner управляет ещё и тем, что переменными не выражено (иконки
 * состояний, тень). С зашитым `theme="dark"` тост оставался тёмным пятном на
 * светлом интерфейсе.
 *
 * --- Почему тост не замечали при открытом модальном окне ---
 *
 * ГЛАВНОЕ — тост и правда лежал ПОД затемнением диалога, и никакой z-index на
 * нём этого не менял. `#root` в `globals.css` объявлен `position: fixed`, а
 * фиксированный элемент создаёт свой контекст наложения. Значит
 * `z-index: 999999999` у контейнера sonner действовал только ВНУТРИ `#root`, а
 * сам `#root` соперничал с затемнением на общих основаниях: `z-index: auto`
 * против `z-50`. Диалог Radix при этом уходит порталом в `body`, то есть в
 * соседи `#root`, а не внутрь него, — и накрывал всё приложение вместе с
 * тостом. Отсюда `createPortal` ниже: тост выносится туда же, в `body`, и
 * только там его z-index встречается с диалогом в одном контексте.
 *
 * Остальные три причины — уже про саму заметность:
 *
 * 1. Фон. `--popover` — нейтральный почти-чёрный, оставшийся от shadcn и в
 *    палитре приложения не участвующий. На затемнённой тёмной теме он давал
 *    тёмный прямоугольник на чуть более тёмном фоне. Теперь `--elevated` —
 *    тот самый токен, который в этом проекте и значит «приподнято над
 *    поверхностью», то есть ровно роль тоста.
 *
 * 2. Цвета не было вообще. Иконки sonner нарисованы через `currentColor`, а
 *    он равен цвету текста, — так что «подключено» и «не удалось» отличались
 *    только рисунком галочки против крестика, в углу, размером 20 пикселей.
 *    Отсюда и «непонятно, есть ли фидбек»: он был, но не сообщал результата.
 *    Теперь тип видно с периферии зрения — по цветной полосе слева и цветной
 *    иконке.
 *
 * 3. Тост нельзя было тронуть. Radix на время модального окна ставит
 *    `pointer-events: none` на `body`, а sonner своему контейнеру `auto` не
 *    ставит: наведение не останавливало таймер, смахнуть тост было нельзя —
 *    он просто истекал. `pointer-events-auto` на самом тосте возвращает и то,
 *    и другое: правило на потомке перебивает запрет с родителя.
 *
 * Текст оставлен `--strong`, а не выкрашен в цвет состояния: `--danger` на
 * `--elevated` даёт около 3.5:1 — для полосы и иконки этого вдоволь, для
 * читаемого текста мало.
 */
const Toaster = ({ ...props }: ToasterProps) => {
  const { theme } = useTheme();
  // В `body`, а не туда, где `<Toaster/>` стоит в дереве: внутри `#root` он
  // заперт в чужом контексте наложения — см. объяснение выше.
  return createPortal(
    <Sonner
      theme={theme}
      className="toaster group"
      toastOptions={{
        classNames: {
          toast: "pointer-events-auto",
          // `!` обязателен у обоих: базовое правило sonner задаёт `border`
          // одной строкой из двух атрибутных селекторов, и одиночному классу
          // Tailwind оно не уступает. Ширина и цвет — разные longhand-свойства,
          // поэтому между собой они не спорят.
          success: "border-l-4! border-l-ok! [&_[data-icon]]:text-ok",
          error: "border-l-4! border-l-danger! [&_[data-icon]]:text-danger",
          warning: "border-l-4! border-l-brand! [&_[data-icon]]:text-brand",
          info: "border-l-4! border-l-brand! [&_[data-icon]]:text-brand",
        },
      }}
      style={
        {
          "--normal-bg": "var(--elevated)",
          "--normal-text": "var(--strong)",
          "--normal-border": "var(--edge)",
        } as React.CSSProperties
      }
      {...props}
    />,
    document.body,
  );
};

export { Toaster };
