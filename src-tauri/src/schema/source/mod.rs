//! Библиотека наборов .proto: откуда файлы берутся и как делятся на контракты.
//!
//! Зачем она вообще. До неё единицей загрузки был ТОПИК: набор копировался в
//! каталог каждого топика, и места, куда положить .proto до выбора топика, в
//! модели не было. На машине владельца это обернулось шестнадцатью каталогами и
//! четырьмя копиями одного `public_events.proto`; на RDP-ферме, где нет
//! чекаутов вовсе, — невозможностью загрузить хоть что-нибудь.
//!
//! Устройство в одну строку: **источник — это дерево, набор — входной файл в
//! нём**. Репозиторий содержит контракты нескольких топиков, и разбирать его
//! целиком нельзя: корней окажется несколько, а правило корня
//! (`proto::linked::Linked::root`) — то, чем приложение определяет тип топика, —
//! работает, только когда корень один. Поэтому дерево делится на наборы по
//! входным файлам (`tree::entries`), и каждый набор разбирается сам по себе.
//!
//! Копий при этом не возникает: дерево лежит в кэше один раз и само служит
//! каталогом включения для всех своих наборов.

