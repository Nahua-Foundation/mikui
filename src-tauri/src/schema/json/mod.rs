//! JSON-Schema-половина схем топиков — третий и последний формат Confluent
//! Schema Registry.
//!
//! Устроена заметно проще двух соседних, и разница принципиальная. Тело Avro и
//! protobuf без схемы не прочитать вовсе: там нет ни имён полей, ни границ
//! значений. Тело JSON Schema читается и без неё — за confluent-заголовком
//! лежит обычный JSON. Поэтому схема здесь стоит только на пути ОТПРАВКИ, а на
//! пути показа таблицы её нет совсем, и `decoder` не хранит ничего.
//!
//! Отсюда и состав: `decoder` снимает заголовок, `compiled` разбирает схему и
//! проверяет ею тело, `template` строит заготовку, `cache` избавляет проверку
//! от похода в реестр на каждое нажатие клавиши.

pub mod cache;
pub mod compiled;
pub mod decoder;
pub mod template;

pub use compiled::Compiled;
pub use decoder::JsonDecoder;
