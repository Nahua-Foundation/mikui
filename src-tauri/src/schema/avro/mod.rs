//! Avro-половина схем топиков.
//!
//! Устроена не так, как protobuf-половина, и вот почему. Тело Avro не несёт
//! своей схемы вообще: это плотно упакованные значения без единого имени поля.
//! Схему кладут рядом, и в Kafka это делают тремя способами, различимыми по
//! первым байтам (см. `wire`). Главный из них — confluent-формат, где в
//! заголовке сообщения едет id схемы в реестре; значит, у одного топика схема
//! может быть СВОЯ НА КАЖДОЕ СООБЩЕНИЕ, и декодер обязан уметь достать её по
//! id прямо во время выдачи окна.
//!
//! Отсюда состав модуля: `registry` ходит в Schema Registry, `cache` держит
//! добытое в памяти и на диске (иначе сеть оказалась бы на пути отрисовки
//! таблицы), `linked` разбирает схему вместе с её зависимостями, `decoder`
//! связывает всё это, а `template` строит заготовку для отправки.

pub mod cache;
pub mod decoder;
pub mod linked;
pub mod registry;
pub mod template;
pub mod wire;

pub use decoder::AvroDecoder;
pub use linked::Linked;
pub use registry::Registry;
